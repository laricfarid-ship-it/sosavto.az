const originalTextNodes = new WeakMap();
function translateText(text, lang) {
  if (!text.trim()) return text;
  const trimmed = text.trim();
  const az = STRINGS[trimmed] ? trimmed : (reverse[trimmed] || trimmed);
  const translated = lang === "az" ? az : STRINGS[az]?.[lang];
  if (!translated) return text;
  return text.replace(trimmed, translated);
}

function excluded(node) {
  return node.closest("script,style,textarea,input,.break,.listing-title,[data-user-content],.user-content,.user-description,.listing-description,[data-user-generated]");
}
function applyLanguage(lang) {
  const root = document.documentElement;
  root.lang = lang;
  const pageTitles = {
    az: "Avtomobil, ehtiyat hissələri və servis — SosAvto.az",
    en: "Cars, spare parts and services — SosAvto.az",
    ru: "Автомобили, запчасти и сервис — SosAvto.az"
  };
  document.title = pageTitles[lang] || pageTitles.az;
  const descriptions = {
    az: "SosAvto.az — Azərbaycanda avtomobil, ehtiyat hissələri, usta, servis və avtoyuma elanları.",
    en: "SosAvto.az — car, spare parts, mechanic, service and car wash listings in Azerbaijan.",
    ru: "SosAvto.az — объявления об автомобилях, запчастях, мастерах, сервисах и автомойках в Азербайджане."
  };
  const descriptionMeta = document.querySelector('meta[name="description"]');
  if (descriptionMeta) descriptionMeta.setAttribute("content", descriptions[lang] || descriptions.az);
  document.querySelectorAll("body *").forEach(el => {
    if (!excluded(el)) {
      for (const node of el.childNodes) {
        if (node.nodeType === Node.TEXT_NODE) {
          if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
          const next = translateText(originalTextNodes.get(node), lang);
          if (node.nodeValue !== next) node.nodeValue = next;
        }
      }
    }
    if (el.hasAttribute("placeholder")) {
      const original = el.getAttribute("data-i18n-placeholder") || el.getAttribute("placeholder");
      if (!el.hasAttribute("data-i18n-placeholder")) el.setAttribute("data-i18n-placeholder", original);
      el.setAttribute("placeholder", translateText(original, lang));
    }
    for (const attr of ["aria-label", "title", "alt"]) {
      if (!el.hasAttribute(attr)) continue;
      const key = "data-i18n-" + attr;
      const original = el.getAttribute(key) || el.getAttribute(attr);
      if (!el.hasAttribute(key)) el.setAttribute(key, original);
      el.setAttribute(attr, translateText(original, lang));
    }
  });
  const picker = document.getElementById("site-language");
  if (picker && picker.value !== lang) picker.value = lang;
}
export function refreshLanguage() {
  applyLanguage(readLanguage());
}
export function initLanguage() {
  window.__sosavtoRefreshLanguage = refreshLanguage;
  const picker = document.getElementById("site-language");
  if (!picker) return;
  let lang = readLanguage();
  if (!["az", "en", "ru"].includes(lang)) lang = "az";
  picker.value = lang;
  applyLanguage(lang);
  picker.onchange = () => {
    lang = picker.value;
    saveLanguage(lang);
    applyLanguage(lang);
  };
  if (!window.__sosavtoLanguageObserver) {
    window.__sosavtoLanguageObserver = new MutationObserver(() => applyLanguage(readLanguage()));
    window.__sosavtoLanguageObserver.observe(document.body, {childList:true,characterData:true,subtree:true});
  }
}
